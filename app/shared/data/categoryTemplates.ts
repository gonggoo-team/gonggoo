/**
 * 카테고리별로 랜덤하게 데이터 선택하는 헬퍼 함수
 */
export const getRandomFromArray = <T>(arr: T[]): T => {
  return arr[Math.floor(Math.random() * arr.length)];
};

export const getCategoryTemplate = (category: string): CategoryTemplate => {
  return CATEGORY_TEMPLATES[category] || CATEGORY_TEMPLATES['기타'];
};
